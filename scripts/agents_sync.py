#!/usr/bin/env python3
"""Generate the single-file guidelines for a tool that loads exactly one instruction file (Junie).

Concatenates `AGENTS.md`, the implementer subset of `agents/common/*.md` and
`agents/junie/INSTRUCTIONS.md` into `agents/junie/GUIDELINES.generated.md`. `--check` regenerates in
memory and fails when the file on disk differs, so `scripts/test.sh` catches drift. Standard library only.

Usage: scripts/agents_sync.py [--check]
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "agents" / "junie" / "GUIDELINES.generated.md"
SOURCES = [
    "AGENTS.md",
    "agents/common/layout.md",
    "agents/common/git-and-hooks.md",
    "agents/junie/INSTRUCTIONS.md",
]
HEADER = (
    "<!-- GENERATED by scripts/agents_sync.py — do not edit by hand. "
    "Run: python3 scripts/agents_sync.py -->\n"
    "# VibeEmulator — Junie guidelines (generated)\n\n"
    "The shared rules and the files a Junie implementer needs, concatenated for a tool that loads\n"
    "exactly one guidelines file. Sources: " + ", ".join(SOURCES) + ".\n"
)


def render() -> str:
    """Return the full generated guidelines text (deterministic, newline-terminated)."""
    parts = [HEADER]
    for rel in SOURCES:
        text = (ROOT / rel).read_text(encoding="utf-8").rstrip("\n")
        parts.append(f"\n---\n\n## From {rel}\n\n{text}\n")
    return "".join(parts)


def main(argv: list[str]) -> int:
    """Write the guidelines file, or with --check compare it and fail on drift."""
    expected = render()
    rel = TARGET.relative_to(ROOT)
    if "--check" in argv:
        if not TARGET.exists():
            print(f"agents_sync: {rel} is missing; run: python3 scripts/agents_sync.py", file=sys.stderr)
            return 1
        if TARGET.read_text(encoding="utf-8") != expected:
            print(f"agents_sync: {rel} is stale; run: python3 scripts/agents_sync.py", file=sys.stderr)
            return 1
        print("agents_sync: guidelines in sync")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(expected, encoding="utf-8")
    print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
